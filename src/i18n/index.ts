export function getCurrentLanguage(): LangKey {
  if (typeof window === 'undefined') return 'zh';
  try {
    const stored = localStorage.getItem('kb-language');
    if (stored === 'zh' || stored === 'en' || stored === 'ja' || stored === 'ko') {
      return stored;
    }
  } catch {
    // ignore
  }
  return 'zh';
}

export function t(key: string, lang?: LangKey): string {
  const language = lang || getCurrentLanguage();
  const dict = translations[language] || translations.zh;
  return dict[key] || translations.zh[key] || key;
}

export function useTranslation() {
  const { language } = useSettings();
  return {
    t: (key: string) => t(key, language),
    language,
  };
}
